"""Checks that only a RENDERED page can answer: text contrast and logo legibility.

Found by the 2026-09-14 cliffordtraining.nl acceptance PDF (after #126):

* the closing CTA's eyebrow "EERST GESPREK" was accent-orange text on an accent-orange
  gradient (painted by ``.cta-section::before``) — every static check passed it, because
  the colours only meet after the cascade, the ``@scope`` wrapper and the pseudo-element
  gradient are resolved;
* the nav showed the source's DARK logo (``logo-clifford.svg``) on a dark navy bar, so
  the brand mark was invisible — although the source ships ``logo-clifford-white.svg``
  for exactly that surface (its own footer used it).

How it measures (no guessing from CSS text):

* the TEXT colour is the browser's computed ``color`` (times ancestor opacity);
* the BACKGROUND is the rendered pixels behind the text: the page is laid out the way
  the design PDF is (print media, desktop width), every text colour is made
  transparent — which moves nothing — and a screenshot is sampled inside each text
  element's box. Gradients, ``::before`` overlays, scrims and photos are measured as
  painted. Resolving backgrounds from computed styles was tried first and misfired on
  the recorded hero: a corner radial glow's accent stop counted as the colour behind a
  headline it never reaches — a false failure that would have failed a healthy job.

Contrast is WCAG 2.x AA — 4.5:1, or 3:1 for large text (>= 24px, or >= 18.66px bold) —
judged at the 10th percentile of the sampled pixels, so one stray border or icon pixel
does not fail a line, while text over the matching half of a gradient does.

Only text a reader can SEE is judged: text clipped to under 2px by its own or an
ancestor's overflow (``sr-only``, a ``max-height: 0`` accordion), ``clip: rect()``,
``clip-path: inset(50%)``, ``display``/``visibility``/``opacity`` hiding, ``aria-hidden``
decoration, transparent text and text outside the page are skipped — measuring them
gave 1.0:1 and failed healthy jobs.

A contrast failure is repaired deterministically first (:func:`fix_contrast_css`: the
nearest page colour token that reaches AA, else the original colour darkened/lightened),
and only what that cannot fix is regenerated by the LLM.

A logo on a surface it cannot be seen on is fixed deterministically (it can be
computed, so it is not re-rolled): the source's own light/dark variant from the image
manifest is swapped in; with no variant, the logo gets a monochrome ``filter``.
"""

