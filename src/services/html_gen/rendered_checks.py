AA_NORMAL = 4.5
AA_LARGE = 3.0
# Percentile of the per-pixel contrast ratios a text box is judged by.
_RATIO_PERCENTILE = 0.10
_SAMPLE_COLS = 16
_SAMPLE_ROWS = 5
# Chromium cannot capture one bitmap taller than its texture limit; capture in slices.
_CAPTURE_SLICE_PX = 4000
_LOGO_ATTR = "data-probe-logo"

# Every text element and logo with its page-coordinate box; logos get marked so the
# capture can hide them.
_COLLECT_JS = r"""([logoAttr, tokenNames]) => {
  const MIN_PX = 2;
  const pageW = document.documentElement.scrollWidth, pageH = document.documentElement.scrollHeight;
  // Hidden by itself or an ancestor: not painted, or deliberately not for a sighted reader.
  const hidden = (el) => {
    for (let n = el; n && n.nodeType === 1; n = n.parentElement) {
      const cs = getComputedStyle(n);
      if (cs.display === 'none' || cs.visibility === 'hidden' || cs.visibility === 'collapse'
        || parseFloat(cs.opacity) === 0 || cs.contentVisibility === 'hidden'
        || n.getAttribute('aria-hidden') === 'true') return true;
    }
    return false;
  };
  // The client-coordinate region NOT clipped away by the element or any ancestor:
  // overflow other than visible, a legacy clip:rect() (sr-only), clip-path: inset().
  const clipRegion = (el) => {
    let l = -Infinity, t = -Infinity, r = Infinity, b = Infinity;
    for (let n = el; n && n.nodeType === 1 && n !== document.body && n !== document.documentElement; n = n.parentElement) {
      const cs = getComputedStyle(n);
      const rc = n.getBoundingClientRect();
      if (cs.overflowX !== 'visible') { l = Math.max(l, rc.left); r = Math.min(r, rc.right); }
      if (cs.overflowY !== 'visible') { t = Math.max(t, rc.top); b = Math.min(b, rc.bottom); }
      if ((cs.position === 'absolute' || cs.position === 'fixed') && cs.clip && cs.clip !== 'auto') {
        const m = cs.clip.match(/rect\(([^)]*)\)/);
        if (m) {
          const v = m[1].split(/[\s,]+/).map((x) => (x === 'auto' ? null : parseFloat(x)));
          if (v[0] !== null) t = Math.max(t, rc.top + v[0]);
          if (v[1] !== null) r = Math.min(r, rc.left + v[1]);
          if (v[2] !== null) b = Math.min(b, rc.top + v[2]);
          if (v[3] !== null) l = Math.max(l, rc.left + v[3]);
        }
      }
      const inset = (cs.clipPath || '').match(/^inset\(\s*([\d.]+)(%|px)/);
      if (inset && ((inset[2] === '%' && parseFloat(inset[1]) >= 50)
        || (inset[2] === 'px' && 2 * parseFloat(inset[1]) >= Math.min(rc.width, rc.height)))) {
        return null;
      }
    }
    return [l, t, r, b];
  };
  // A client rect cut to the clip region and the page, in PAGE coordinates; null if
  // less than MIN_PX survives in either direction.
  const visibleBox = (rect, region) => {
    if (!region) return null;
    const l = Math.max(rect.left, region[0], -scrollX), t = Math.max(rect.top, region[1], -scrollY);
    const r = Math.min(rect.right, region[2], pageW - scrollX), b = Math.min(rect.bottom, region[3], pageH - scrollY);
    if (r - l < MIN_PX || b - t < MIN_PX) return null;
    return [l + scrollX, t + scrollY, r - l, b - t];
  };
  const box = (el) => { const r = el.getBoundingClientRect(); return [r.left + scrollX, r.top + scrollY, r.width, r.height]; };
  // The VISIBLE parts of the element's OWN text runs (line boxes tight around the
  // glyphs), so a round avatar's corners or a wide paragraph's margin are not sampled.
  const textBoxes = (el, region) => {
    const out = [];
    for (const n of el.childNodes) {
      if (n.nodeType !== 3 || !n.textContent.trim()) continue;
      const range = document.createRange(); range.selectNodeContents(n);
      for (const r of range.getClientRects()) {
        const vb = visibleBox(r, region);
        if (vb && out.length < 12) out.push(vb);
      }
    }
    return out;
  };
  const sectionOf = (el) => { const s = el.closest('[data-section]'); return s ? s.getAttribute('data-section') : null; };
  // A selector for exactly this element, relative to its [data-section] wrapper, that
  // the section's @scope-d CSS can target.
  const pathOf = (el) => {
    const root = el.closest('[data-section]');
    const parts = [];
    for (let n = el; n && n !== root; n = n.parentElement) {
      const p = n.parentElement;
      if (!p) return '';
      const same = [...p.children].filter((c) => c.tagName === n.tagName);
      parts.unshift(`${n.tagName.toLowerCase()}:nth-of-type(${same.indexOf(n) + 1})`);
    }
    return parts.length ? ':scope > ' + parts.join(' > ') : '';
  };
  const texts = [];
  for (const el of document.querySelectorAll('[data-section] *')) {
    if (['STYLE', 'SCRIPT', 'NOSCRIPT', 'TITLE', 'TEMPLATE'].includes(el.tagName)) continue;
    const own = [...el.childNodes].filter((n) => n.nodeType === 3).map((n) => n.textContent).join('').trim();
    if (!own || !/[\p{L}\p{N}]/u.test(own) || hidden(el)) continue;
    const cs = getComputedStyle(el);
    if ((cs.webkitBackgroundClip || cs.backgroundClip || '').includes('text')) continue;
    const boxes = textBoxes(el, clipRegion(el));
    if (!boxes.length) continue;
    let opacity = 1;
    for (let n = el; n && n.nodeType === 1; n = n.parentElement) opacity *= parseFloat(getComputedStyle(n).opacity);
    const cls = typeof el.className === 'string' && el.className.trim() ? '.' + el.className.trim().split(/\s+/).join('.') : '';
    texts.push({
      section: sectionOf(el), text: own.slice(0, 60), color: cs.webkitTextFillColor || cs.color, opacity,
      size: parseFloat(cs.fontSize), weight: parseInt(cs.fontWeight, 10) || 400,
      selector: el.tagName.toLowerCase() + cls, path: pathOf(el), boxes,
    });
  }
  const logos = [];
  for (const img of document.querySelectorAll('[data-section] img')) {
    const src = img.getAttribute('src') || '';
    const name = (src.split('?')[0].split('/').pop() || '').toLowerCase();
    const cls = (typeof img.className === 'string' ? img.className : '').toLowerCase();
    if (!(name.includes('logo') || cls.includes('logo')) || hidden(img)) continue;
    const vb = visibleBox(img.getBoundingClientRect(), clipRegion(img));
    if (!vb) continue;
    img.setAttribute(logoAttr, '');
    logos.push({ section: sectionOf(img), src, box: vb });
  }
  // The page's resolved colour tokens: the palette a deterministic contrast fix picks from.
  const palette = {};
  const swatch = document.createElement('span');
  document.body.appendChild(swatch);
  for (const name of tokenNames) {
    swatch.style.color = '';
    swatch.style.color = `var(${name})`;
    const v = getComputedStyle(swatch).color;
    if (getComputedStyle(document.documentElement).getPropertyValue(name).trim()) palette[name] = v;
  }
  swatch.remove();
  return { texts, logos, palette, height: document.documentElement.scrollHeight, width: document.documentElement.scrollWidth };
}"""

# Make text and logos disappear WITHOUT moving anything, so the pixels left are the
# backgrounds they sit on.
_HIDE_FOREGROUND_CSS = f"""
[data-section] *, [data-section] *::before, [data-section] *::after {{
  color: transparent !important; -webkit-text-fill-color: transparent !important;
  text-shadow: none !important; text-decoration-color: transparent !important;
  caret-color: transparent !important; }}
[data-section] img[{_LOGO_ATTR}] {{ visibility: hidden !important; }}
"""


_HIDE_FOREGROUND_INLINE_JS = """() => {
  for (const el of document.querySelectorAll('[data-section] *')) {
    el.style.setProperty('color', 'transparent', 'important');
    el.style.setProperty('-webkit-text-fill-color', 'transparent', 'important');
    el.style.setProperty('text-shadow', 'none', 'important');
    el.style.setProperty('text-decoration-color', 'transparent', 'important');
  }
}"""


@dataclass(frozen=True)
class ContrastFailure:
    """One text element below WCAG AA on the rendered page."""

    section: str | None
    text: str
    ratio: float
    required: float
    color: str
    background: str
    selector: str
    # ``:scope > div:nth-of-type(1) > p:nth-of-type(2)`` relative to the section wrapper
    # (empty when unknown) — what a deterministic CSS fix targets.
    path: str = ""
    # EVERY backdrop pixel sampled behind the text, not just the 10th-percentile one in
    # ``background``: a recolour must pass against the same distribution it is judged
    # by, or it trades a failure on one part of the backdrop for one on another.
    backdrop: tuple[tuple[float, float, float], ...] = field(default=(), compare=False, repr=False)

    def describe(self) -> str:
        return (
            f"{self.selector} {self.text!r} is {self.color} on {self.background}: contrast "
            f"{self.ratio}:1, WCAG AA needs {self.required}:1"
        )


@dataclass(frozen=True)
class LogoPlacement:
    """A logo image and the luminance (0 dark .. 1 light) of the surface under it."""

    section: str | None
    src: str
    surface_luminance: float


@dataclass
class RenderedReport:
    """What :func:`measure_rendered_page` measured."""

    contrast: list[ContrastFailure] = field(default_factory=list)
    logos: list[LogoPlacement] = field(default_factory=list)
    # Resolved page colour tokens (``--color-ink`` -> ``rgb(26, 26, 26)``).
    palette: dict[str, str] = field(default_factory=dict)

    def contrast_by_section(self) -> dict[str, list[str]]:
        out: dict[str, list[str]] = {}
        for f in self.contrast:
            if f.section:
                bucket = out.setdefault(f.section, [])
                if len(bucket) < 8:
                    bucket.append(f.describe())
        return out


_RGBA_RE = re.compile(
    r"rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)"
)
_SRGB_RE = re.compile(r"color\(\s*srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*/\s*([\d.]+%?))?\s*\)")

Rgb = tuple[float, float, float]


def _alpha(value: str | None) -> float:
    if value is None:
        return 1.0
    return float(value[:-1]) / 100 if value.endswith("%") else float(value)


def parse_css_color(value: str) -> tuple[float, float, float, float] | None:
    """A computed CSS colour (``rgb()``/``rgba()``/``color(srgb …)``) as ``(r, g, b, a)``."""
    m = _RGBA_RE.search(value or "")
    if m:
        return float(m[1]), float(m[2]), float(m[3]), _alpha(m[4])
    m = _SRGB_RE.search(value or "")
    if m:
        return float(m[1]) * 255, float(m[2]) * 255, float(m[3]) * 255, _alpha(m[4])
    return None


def _luminance(rgb: Rgb) -> float:
    def channel(v: float) -> float:
        v /= 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4

    return 0.2126 * channel(rgb[0]) + 0.7152 * channel(rgb[1]) + 0.0722 * channel(rgb[2])


def _ratio(a: Rgb, b: Rgb) -> float:
    la, lb = _luminance(a), _luminance(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def _over(fg: tuple[float, float, float, float], bg: Rgb) -> Rgb:
    a = fg[3]
    return (fg[0] * a + bg[0] * (1 - a), fg[1] * a + bg[1] * (1 - a), fg[2] * a + bg[2] * (1 - a))


class _Pixels:
    """Background pixels of the whole page, captured in vertical slices."""

    def __init__(self, slices: list[tuple[int, Any]]) -> None:
        self._slices = slices  # (top_y, PIL RGB image)

    def at(self, x: float, y: float) -> Rgb | None:
        for top, img in self._slices:
            if top <= y < top + img.height:
                xi, yi = int(x), int(y - top)
                if 0 <= xi < img.width and 0 <= yi < img.height:
                    r, g, b = img.getpixel((xi, yi))[:3]
                    return float(r), float(g), float(b)
        return None

    def sample(self, box: list[float]) -> list[Rgb]:
        x, y, w, h = box
        points = (
            self.at(x + w * (i + 0.5) / _SAMPLE_COLS, y + h * (j + 0.5) / _SAMPLE_ROWS)
            for i in range(_SAMPLE_COLS)
            for j in range(_SAMPLE_ROWS)
        )
        return [p for p in points if p is not None]


class _TextItem(TypedDict):
    """One text element as :data:`_COLLECT_JS` reports it."""

    section: str | None
    text: str
    color: str
    opacity: float
    size: float
    weight: int
    selector: str
    path: str
    boxes: list[list[float]]


# Text whose painted alpha is below this is not visible text (``color: transparent``).
_MIN_VISIBLE_ALPHA = 0.02


def _judge_text(item: _TextItem, pixels: _Pixels) -> ContrastFailure | None:
    fg = parse_css_color(str(item.get("color", "")))
    samples = [px for box in item.get("boxes") or [] for px in pixels.sample(box)]
    if fg is None or not samples:
        return None
    fg = (fg[0], fg[1], fg[2], fg[3] * float(item.get("opacity", 1.0)))
    if fg[3] < _MIN_VISIBLE_ALPHA:
        return None
    size, weight = float(item.get("size", 16)), int(item.get("weight", 400))
    required = AA_LARGE if size >= 24 or (weight >= 700 and size >= 18.66) else AA_NORMAL
    scored = sorted((_ratio(_over(fg, bg), bg), bg) for bg in samples)
    ratio, bg = scored[int(len(scored) * _RATIO_PERCENTILE)]
    if ratio + 1e-6 >= required:
        return None
    return ContrastFailure(
        section=item.get("section"),
        text=str(item.get("text", "")),
        ratio=round(ratio, 2),
        required=required,
        color=str(item.get("color", "")),
        background="rgb({}, {}, {})".format(*(round(c) for c in bg)),
        selector=str(item.get("selector", "")),
        path=str(item.get("path", "")),
        backdrop=tuple(samples),
    )


def _judged_ratio(fg: Rgb, backdrop: list[Rgb]) -> float:
    """Opaque ``fg``'s contrast over ``backdrop`` at the percentile text is judged by."""
    scored = sorted(_ratio(fg, bg) for bg in backdrop)
    return scored[int(len(scored) * _RATIO_PERCENTILE)]


async def _capture_backgrounds(page: Page, width: int, height: int) -> _Pixels:
    from PIL import Image

    await page.add_style_tag(content=_HIDE_FOREGROUND_CSS)
    # INLINE !important too: a section's own ``color: … !important`` (the computed
    # contrast fix writes exactly that) outranks a stylesheet !important by specificity
    # and would leave its text painted into the "background" capture.
    await page.evaluate(_HIDE_FOREGROUND_INLINE_JS)
    slices: list[tuple[int, Any]] = []
    for top in range(0, max(height, 1), _CAPTURE_SLICE_PX):
        clip: FloatRect = {
            "x": 0,
            "y": top,
            "width": width,
            "height": min(_CAPTURE_SLICE_PX, height - top),
        }
        png = await page.screenshot(clip=clip, full_page=True, animations="disabled")
        slices.append((top, Image.open(io.BytesIO(png)).convert("RGB")))
    return _Pixels(slices)


async def measure_rendered_page(page: Page) -> RenderedReport:
    """Measure a page that is already loaded and laid out (see the module docstring).

    Leaves the page with its text hidden — use a page you are done with.
    """
    from .brand_css import BRAND_TOKEN_NAMES

    color_tokens = sorted(n for n in BRAND_TOKEN_NAMES if n.startswith("--color-"))
    collected = await page.evaluate(_COLLECT_JS, [_LOGO_ATTR, color_tokens])
    pixels = await _capture_backgrounds(
        page, int(collected.get("width") or 1440), int(collected.get("height") or 1)
    )
    report = RenderedReport(palette=dict(collected.get("palette") or {}))
    for item in collected.get("texts") or []:
        failure = _judge_text(item, pixels)
        if failure is not None:
            report.contrast.append(failure)
    for logo in collected.get("logos") or []:
        samples = pixels.sample(logo["box"])
        if samples:
            report.logos.append(
                LogoPlacement(
                    section=logo.get("section"),
                    src=str(logo["src"]),
                    surface_luminance=sum(_luminance(s) for s in samples) / len(samples),
                )
            )
    return report


async def probe_rendered_page(html: str, *, layout_width_px: int = 1440) -> RenderedReport:
    """Render ``html`` the way the design PDF is laid out and measure it.

    Same sink as ``render_pdf_from_html_string``: a temp ``file://`` page in the shared
    browser pool, print media at the desktop layout width, private subresources refused.
    """
    import tempfile

    from src.services.browser_pool import get_browser_pool
    from src.services.screenshot_renderer import (
        _close_page_quietly,
        _minio_allow_hosts,
        block_private_subresources,
    )

    with tempfile.NamedTemporaryFile(suffix=".html", delete=False, mode="w", encoding="utf-8") as f:
        f.write(html)
        temp_path = Path(f.name)
    try:
        pool = await get_browser_pool()
        async with pool.lease() as browser:
            page = await browser.new_page(viewport={"width": layout_width_px, "height": 1024})
            try:
                await block_private_subresources(page, allow_hosts=_minio_allow_hosts())
                try:
                    await page.goto(
                        f"file://{temp_path.resolve()}", wait_until="networkidle", timeout=60000
                    )
                except Exception as exc:  # noqa: BLE001 — a slow image must not skip the check
                    logger.warning("rendered probe: page load incomplete (%s); measuring", exc)
                await page.emulate_media(media="print")
                return await measure_rendered_page(page)
            finally:
                await _close_page_quietly(page)
    finally:
        temp_path.unlink(missing_ok=True)


# A logo file named like this is the variant for DARK surfaces.
_LIGHT_VARIANT_RE = re.compile(
    r"(?:^|[-_.])(white|wit|light|licht|inverse|inverted|negative|neg|reversed?|mono-?white|on-?dark)(?=[-_.]|$)",
    re.IGNORECASE,
)
_DARK_SURFACE = 0.25
_LIGHT_SURFACE = 0.6
_ON_DARK_FILTER = "filter: brightness(0) invert(1);"
_ON_LIGHT_FILTER = "filter: brightness(0);"


def _file_name(url: str) -> str:
    return url.split("?", 1)[0].rsplit("/", 1)[-1]


def _is_light_variant(url: str) -> bool:
    return bool(_LIGHT_VARIANT_RE.search(_file_name(url).rsplit(".", 1)[0]))


def _logo_urls(manifest: list[dict]) -> list[str]:
    return [
        str(m["url"])
        for m in manifest
        if m.get("url") and ("logo" in _file_name(str(m["url"])).lower() or m.get("role") == "logo")
    ]


def _variant_for(src: str, *, want_light: bool, manifest: list[dict]) -> str | None:
    candidates = [
        u for u in _logo_urls(manifest) if u != src and _is_light_variant(u) == want_light
    ]
    if not candidates:
        return None
    stem = _LIGHT_VARIANT_RE.sub("", _file_name(src).rsplit(".", 1)[0]).lower()
    for url in candidates:
        if _LIGHT_VARIANT_RE.sub("", _file_name(url).rsplit(".", 1)[0]).lower() == stem:
            return url
    return candidates[0]


def _retarget(placement: LogoPlacement) -> tuple[bool, str] | None:
    """``(want_light_variant, fallback_filter)`` when the logo is unreadable, else None."""
    light = _is_light_variant(placement.src)
    if placement.surface_luminance < _DARK_SURFACE and not light:
        return True, _ON_DARK_FILTER
    if placement.surface_luminance > _LIGHT_SURFACE and light:
        return False, _ON_LIGHT_FILTER
    return None


def _rewrite_logo(fragment: str, src: str, variant: str | None, tint: str) -> str | None:
    """``fragment`` with every ``<img src=src>`` swapped to ``variant`` (or tinted)."""
    from bs4 import BeautifulSoup

    soup = BeautifulSoup(fragment, "html.parser")
    imgs = [img for img in soup.find_all("img", src=True) if str(img.get("src")) == src]
    for img in imgs:
        if variant:
            img["src"] = variant
            if img.get("srcset"):
                del img["srcset"]
            continue
        style = str(img.get("style") or "").rstrip()
        if "filter" not in style:
            img["style"] = f"{style}{';' if style and not style.endswith(';') else ''}{tint}"
    return str(soup) if imgs else None


def fix_logo_surfaces(
    sections: dict[str, str], report: RenderedReport, manifest: list[dict]
) -> tuple[dict[str, str], list[str]]:
    """Swap/tint every logo that sits on a surface it cannot be read on.

    Returns ``(sections, changes)``; ``sections`` is always a new dict.
    """
    out = dict(sections)
    changes: list[str] = []
    for placement in report.logos:
        key = placement.section
        target = _retarget(placement)
        if key is None or key not in out or target is None:
            continue
        want_light, tint = target
        variant = _variant_for(placement.src, want_light=want_light, manifest=manifest)
        rewritten = _rewrite_logo(out[key], placement.src, variant, tint)
        if rewritten is None:
            continue
        out[key] = rewritten
        surface = "dark" if want_light else "light"
        fix = f"swapped to {variant}" if variant else "tinted monochrome"
        changes.append(f"{key}: logo {placement.src} on a {surface} surface — {fix}")
    return out, changes


# ── deterministic contrast repair (the cheap fix, tried BEFORE an LLM regeneration) ──

# Aim a little above the AA threshold, so the 10th-percentile re-measurement of the
# same text over the same pixels does not land a hair under it.
_CONTRAST_MARGIN = 0.3
_MIX_STEPS = 20
# Tokens meant to colour TEXT (surface/card/border tokens are not candidates).
_TEXT_ROLE_TOKENS = frozenset(
    {
        "--color-on-brand",
        "--color-on-accent",
        "--color-ink",
        "--color-text",
        "--color-text-muted",
        "--color-muted",
        "--color-accent-text",
        "--color-brand",
        "--color-accent",
    }
)


def _hex(rgb: Rgb) -> str:
    return "#{:02x}{:02x}{:02x}".format(*(max(0, min(255, round(c))) for c in rgb))


def _mix(a: Rgb, b: Rgb, t: float) -> Rgb:
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t)


def _distance(a: Rgb, b: Rgb) -> float:
    """How different two text colours LOOK: RGB distance, with a change of colourfulness
    weighted double — grey text should become ink, not the accent orange."""
    rgb = sum((x - y) ** 2 for x, y in zip(a, b, strict=True)) ** 0.5
    return rgb + 2 * abs((max(a) - min(a)) - (max(b) - min(b)))


def fixed_text_color(
    color: str,
    background: str,
    required: float,
    palette: dict[str, str],
    backdrop: Sequence[Rgb] = (),
) -> str | None:
    """A text colour that reaches ``required`` (+ margin) on the backdrop, else ``None``.

    Brand first: the page TEXT colour token (``var(--color-…)``) closest to the original
    colour (:func:`_distance`) that reaches the target. Only when no token does, the original colour is
    darkened or lightened — whichever needs the smaller shift, so its hue survives.

    A candidate is judged against EVERY sampled backdrop pixel (``backdrop``) at the
    same percentile :func:`_judge_text` uses — not against ``background``, which is only
    the worst-scoring sample of the ORIGINAL colour. Judging one sample is what painted
    white hero text ``--color-muted`` (#555) on 2026-10-18: the white text's worst
    sample was a white chat panel overlapping the navy hero, so #555 "passed" there and
    then failed 2.41:1 on the navy everywhere else, three rounds running. With no
    ``backdrop`` (older callers), ``background`` alone is the backdrop.
    """
    fg = parse_css_color(color)
    bg = parse_css_color(background)
    if fg is None or bg is None:
        return None
    fg_rgb: Rgb = (fg[0], fg[1], fg[2])
    samples: list[Rgb] = list(backdrop) or [(bg[0], bg[1], bg[2])]
    target = required + _CONTRAST_MARGIN
    tokens = []
    for name, value in palette.items():
        if name not in _TEXT_ROLE_TOKENS:
            continue
        parsed = parse_css_color(value)
        if parsed is None or parsed[3] < 0.99:
            continue
        rgb: Rgb = (parsed[0], parsed[1], parsed[2])
        if _judged_ratio(rgb, samples) >= target:
            tokens.append((_distance(rgb, fg_rgb), name))
    if tokens:
        return f"var({min(tokens)[1]})"
    shifts = []
    for toward in ((0.0, 0.0, 0.0), (255.0, 255.0, 255.0)):
        for step in range(1, _MIX_STEPS + 1):
            candidate = _mix(fg_rgb, toward, step / _MIX_STEPS)
            if _judged_ratio(candidate, samples) >= target:
                shifts.append((step, _hex(candidate)))
                break
    return min(shifts)[1] if shifts else None


def fix_contrast_css(
    sections: dict[str, str], report: RenderedReport
) -> tuple[dict[str, str], list[str], dict[str, list[str]]]:
    """Recolour every contrast failure that a colour change can fix, with section CSS.

    Returns ``(sections, changes, unfixable)``: ``sections`` is a new dict (a
    ``<style>`` appended to each fixed section, targeting the exact element by its
    path under the section wrapper — the section's CSS is ``@scope``-d there at
    composition); ``unfixable`` names the failures no colour fixes, by section. The
    page must be re-measured: this is computed from one backdrop sample.
    """
    out = dict(sections)
    rules: dict[str, dict[str, str]] = {}
    changes: list[str] = []
    unfixable: dict[str, list[str]] = {}
    for failure in report.contrast:
        key = failure.section
        if key is None or key not in out:
            continue
        new = (
            fixed_text_color(
                failure.color,
                failure.background,
                failure.required,
                report.palette,
                failure.backdrop,
            )
            if failure.path
            else None
        )
        if new is None:
            unfixable.setdefault(key, []).append(failure.describe())
            continue
        rules.setdefault(key, {})[failure.path] = new
        changes.append(
            f"{key}: {failure.selector} {failure.text!r} {failure.color} on "
            f"{failure.background} -> {new}"
        )
    for key, by_path in rules.items():
        css = "\n".join(
            f"{path} {{ color: {c} !important; -webkit-text-fill-color: {c} !important; }}"
            for path, c in by_path.items()
        )
        out[key] = f"{out[key]}\n<style>/* rendered contrast fix */\n{css}\n</style>"
    return out, changes, unfixable
